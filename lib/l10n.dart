import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// 轻量应用内 i18n: 中文/英文两种语言, 默认中文, SharedPreferences 持久化。
/// 根 MaterialApp 包在 ListenableBuilder(listenable: l10n) 里, 切换语言整树重建。
class L10n extends ChangeNotifier {
  String lang = 'zh';

  bool get isEn => lang == 'en';

  Future<void> init() async {
    final sp = await SharedPreferences.getInstance();
    lang = sp.getString('appLang') ?? 'zh';
  }

  Future<void> setLang(String v) async {
    if (v == lang) return;
    lang = v;
    notifyListeners();
    (await SharedPreferences.getInstance()).setString('appLang', v);
  }
}

final l10n = L10n();

/// 取翻译: 当前语言 → 中文 → key 本身兜底
String tr(String key) => (l10n.isEn ? _en[key] : null) ?? _zh[key] ?? key;

/// 带占位符的翻译: trf('sent_files', {'n': 3}) → 已发送3个文件请求
String trf(String key, Map<String, Object> args) {
  var s = tr(key);
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

